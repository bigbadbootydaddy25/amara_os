MARKETS_BY_NAME: dict[str, Market] = {m.name: m for m in MARKETS}
MARKETS_BY_REGION: dict[str, list[Market]] = {}
for _m in MARKETS:
    MARKETS_BY_REGION.setdefault(_m.region, []).append(_m)


def get_all_zips() -> list[tuple[str, Market]]:
    """Returns flat list of (zip, market) tuples."""
    result = []
    for market in MARKETS:
        for z in market.zips:
            result.append((z, market))
    return result


def get_zips_by_region(region: str) -> list[tuple[str, Market]]:
    result = []
    for market in MARKETS_BY_REGION.get(region, []):
        for z in market.zips:
            result.append((z, market))
    return result
